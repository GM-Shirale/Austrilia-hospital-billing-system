    ('LIPID', 'Lipid Studies',                             'Biochemistry', 'PATHOLOGY',  50.00, '66503', 11.90),
    ('TROP',  'High-sensitivity Troponin',                 'Cardiac',      'PATHOLOGY',  95.00, '66518', 29.05),
    ('CXR',   'Chest X-Ray',                               'Imaging',      'IMAGING',   150.00, '58503', 47.15),
    ('ECG',   '12-lead ECG',                               'Cardiac',      'DIAGNOSTIC', 85.00, '11714', 32.50)
