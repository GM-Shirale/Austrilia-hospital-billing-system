-- ---------------------------------------------------------------------
-- Lab test catalogue: type, GST flag, active flag
-- ---------------------------------------------------------------------
ALTER TABLE lab_test
    ADD COLUMN test_type VARCHAR(20) NOT NULL DEFAULT 'PATHOLOGY',
    ADD COLUMN gst_free  BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD COLUMN active    BOOLEAN     NOT NULL DEFAULT TRUE;
ALTER TABLE lab_test ADD CONSTRAINT ck_lab_test_type CHECK (test_type IN ('PATHOLOGY', 'IMAGING', 'DIAGNOSTIC'));

UPDATE lab_test SET test_type = 'IMAGING'    WHERE category ILIKE 'imaging%' OR category ILIKE 'radiology%';
UPDATE lab_test SET test_type = 'DIAGNOSTIC' WHERE test_code = 'ECG';

-- ---------------------------------------------------------------------
-- Lab order audit trail
-- ---------------------------------------------------------------------
ALTER TABLE lab_order
    ADD COLUMN ordered_by_user_id   BIGINT REFERENCES app_user (id),
    ADD COLUMN ordered_by_name      VARCHAR(120),
    ADD COLUMN collected_by_user_id BIGINT REFERENCES app_user (id),
    ADD COLUMN collected_by_name    VARCHAR(120),
    ADD COLUMN collected_at         TIMESTAMP,
    ADD COLUMN performed_by_user_id BIGINT REFERENCES app_user (id),
    ADD COLUMN performed_by_name    VARCHAR(120),
    ADD COLUMN completed_at         TIMESTAMP,
    ADD COLUMN result_notes         VARCHAR(1000),
    ADD COLUMN cancelled_by_name    VARCHAR(120),
    ADD COLUMN cancelled_at         TIMESTAMP;

ALTER TABLE lab_order_item
    ADD COLUMN resulted_by_name VARCHAR(120),
    ADD COLUMN resulted_at      TIMESTAMP;

CREATE INDEX ix_lab_order_queue ON lab_order (tenant_id, status, order_date);

-- ---------------------------------------------------------------------
-- Medicine catalogue: GST classification (Australian GST Act)
--   PBS            PBS-listed medicine                       GST-free
--   PRESCRIPTION   prescription-only (non-PBS) on a script   GST-free
--   OTC            over-the-counter product                  10% GST
--   TAXABLE_SUPPLY general / non-medical goods               10% GST
-- gst_rate is kept (the billing engine reads it) and must match the category.
-- ---------------------------------------------------------------------
ALTER TABLE medicine
    ADD COLUMN supply_category        VARCHAR(20) NOT NULL DEFAULT 'PBS',
    ADD COLUMN pbs_item_code          VARCHAR(10),
    ADD COLUMN active                 BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD COLUMN stock_adjusted_by_name VARCHAR(120),
    ADD COLUMN stock_adjusted_at      TIMESTAMP;

UPDATE medicine SET supply_category = CASE WHEN gst_rate > 0 THEN 'TAXABLE_SUPPLY' ELSE 'PBS' END;
UPDATE medicine SET gst_rate = CASE WHEN supply_category IN ('PBS', 'PRESCRIPTION') THEN 0 ELSE 0.1 END;

ALTER TABLE medicine ADD CONSTRAINT ck_medicine_supply_category
    CHECK (supply_category IN ('PBS', 'PRESCRIPTION', 'OTC', 'TAXABLE_SUPPLY'));
ALTER TABLE medicine ADD CONSTRAINT ck_medicine_gst_matches_category
    CHECK ((supply_category IN ('PBS', 'PRESCRIPTION') AND gst_rate = 0)
        OR (supply_category IN ('OTC', 'TAXABLE_SUPPLY') AND gst_rate = 0.1));

-- ---------------------------------------------------------------------
-- Prescription audit trail
-- ---------------------------------------------------------------------
ALTER TABLE pharmacy_prescription
    ADD COLUMN prescribed_by_user_id BIGINT REFERENCES app_user (id),
    ADD COLUMN prescribed_by_name    VARCHAR(120),
    ADD COLUMN dispensed_by_user_id  BIGINT REFERENCES app_user (id),
    ADD COLUMN dispensed_by_name     VARCHAR(120),
    ADD COLUMN dispensed_at          TIMESTAMP,
    ADD COLUMN cancelled_by_name     VARCHAR(120),
    ADD COLUMN cancelled_at          TIMESTAMP;

CREATE INDEX ix_prescription_queue ON pharmacy_prescription (tenant_id, status, prescription_date);

-- ---------------------------------------------------------------------
-- Stock ledger: every change to stock_quantity, with who and why
-- ---------------------------------------------------------------------
CREATE TABLE medicine_stock_movement (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           UUID            NOT NULL REFERENCES hospital (id),
    medicine_id         BIGINT          NOT NULL REFERENCES medicine (id),
    movement_type       VARCHAR(20)     NOT NULL,      -- OPENING | RECEIPT | ADJUSTMENT | DISPENSE
    quantity_delta      INTEGER         NOT NULL,
    balance_after       INTEGER         NOT NULL CHECK (balance_after >= 0),
    reason              VARCHAR(250),
    prescription_id     BIGINT          REFERENCES pharmacy_prescription (id),
    performed_by_user_id BIGINT         REFERENCES app_user (id),
    performed_by_name   VARCHAR(120)    NOT NULL,
    performed_at        TIMESTAMP       NOT NULL,
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    version             BIGINT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_stock_movement_type CHECK (movement_type IN ('OPENING', 'RECEIPT', 'ADJUSTMENT', 'DISPENSE'))
);
CREATE INDEX ix_stock_movement_medicine ON medicine_stock_movement (tenant_id, medicine_id, performed_at);
CREATE INDEX ix_stock_movement_prescription ON medicine_stock_movement (prescription_id);

