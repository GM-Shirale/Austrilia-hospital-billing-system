-- ---------------------------------------------------------------------
-- Doctor weekly schedule (roster)
-- ---------------------------------------------------------------------
CREATE TABLE doctor_schedule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID            NOT NULL REFERENCES hospital (id),
    doctor_id       BIGINT          NOT NULL REFERENCES doctor (id),
    day_of_week     VARCHAR(10)     NOT NULL,          -- MONDAY .. SUNDAY (java.time.DayOfWeek)
    start_time      TIME            NOT NULL,
    end_time        TIME            NOT NULL,
    slot_minutes    INTEGER         NOT NULL DEFAULT 15 CHECK (slot_minutes BETWEEN 5 AND 120),
    location        VARCHAR(100),
    active          BOOLEAN         NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    version         BIGINT          NOT NULL DEFAULT 0,
    CONSTRAINT ck_schedule_times CHECK (end_time > start_time),
    CONSTRAINT ck_schedule_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);
CREATE INDEX ix_schedule_tenant_doctor ON doctor_schedule (tenant_id, doctor_id, day_of_week);

-- ---------------------------------------------------------------------
-- Consultations (doctor attendances) attached to an admission
-- ---------------------------------------------------------------------
CREATE TABLE consultation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           UUID            NOT NULL REFERENCES hospital (id),
    consultation_no     VARCHAR(30)     NOT NULL,
    admission_id        BIGINT          NOT NULL REFERENCES admission (id),
    doctor_id           BIGINT          NOT NULL REFERENCES doctor (id),
    consultation_type   VARCHAR(20)     NOT NULL,      -- INITIAL | FOLLOW_UP | SPECIALIST_REVIEW | TELEHEALTH
    consultation_at     TIMESTAMP       NOT NULL,
    mbs_item_no         VARCHAR(10)     NOT NULL,
    mbs_schedule_fee    NUMERIC(12,2)   NOT NULL CHECK (mbs_schedule_fee >= 0),
    fee                 NUMERIC(12,2)   NOT NULL CHECK (fee >= 0),
    notes               VARCHAR(500),
    status              VARCHAR(20)     NOT NULL DEFAULT 'COMPLETED',  -- COMPLETED | CANCELLED
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    version             BIGINT          NOT NULL DEFAULT 0,
    CONSTRAINT uk_consultation_no UNIQUE (tenant_id, consultation_no)
);
CREATE INDEX ix_consultation_tenant_admission ON consultation (tenant_id, admission_id);
CREATE INDEX ix_consultation_doctor_time ON consultation (tenant_id, doctor_id, consultation_at);

