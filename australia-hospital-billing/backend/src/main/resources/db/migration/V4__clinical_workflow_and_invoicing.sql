-- payment_status describes the PATIENT's share (what the tax invoice shows as "balance due"):
--   PENDING = nothing paid yet, PARTIAL = part paid, FULL = patient share settled.
ALTER TABLE hospital_bill
    ADD COLUMN patient_paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    ADD COLUMN payment_status      VARCHAR(10)   NOT NULL DEFAULT 'PENDING',
    ADD COLUMN charges_locked_at   TIMESTAMP;
ALTER TABLE hospital_bill ADD CONSTRAINT ck_bill_payment_status
    CHECK (payment_status IN ('PENDING', 'PARTIAL', 'FULL'));

UPDATE hospital_bill b
SET patient_paid_amount = COALESCE((SELECT SUM(p.amount - p.refunded_amount)
                                    FROM payment p
                                    WHERE p.hospital_bill_id = b.id AND p.paid_by = 'PATIENT'), 0);

UPDATE hospital_bill
SET payment_status = CASE
        WHEN status IN ('DRAFT', 'CANCELLED') THEN 'PENDING'
        WHEN patient_paid_amount >= patient_payable_amount THEN 'FULL'
        WHEN patient_paid_amount > 0 THEN 'PARTIAL'
        ELSE 'PENDING' END;

